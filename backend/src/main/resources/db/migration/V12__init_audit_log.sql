CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id BIGINT,
    operator_type VARCHAR(32) NOT NULL,
    action_type VARCHAR(64) NOT NULL,
    resource_type VARCHAR(64) NOT NULL,
    resource_id VARCHAR(128),
    request_id VARCHAR(96),
    detail_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_audit_log_public_id UNIQUE (public_id),
    CONSTRAINT fk_audit_log_user_id FOREIGN KEY (user_id) REFERENCES user_account (id)
);

CREATE INDEX idx_audit_log_created_at
    ON audit_log (created_at DESC);

CREATE INDEX idx_audit_log_operator_created
    ON audit_log (operator_type, created_at DESC);

CREATE INDEX idx_audit_log_resource
    ON audit_log (resource_type, resource_id, created_at DESC);

CREATE INDEX idx_audit_log_request_id
    ON audit_log (request_id);
