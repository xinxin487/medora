CREATE TABLE agent_trace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    trace_id VARCHAR(96) NOT NULL,
    conversation_id BIGINT NOT NULL,
    message_id BIGINT,
    intent_type VARCHAR(64) NOT NULL,
    route_mode VARCHAR(64) NOT NULL,
    retrieval_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    tool_events_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    latency_ms BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    error_message VARCHAR(512),
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_agent_trace_public_id UNIQUE (public_id),
    CONSTRAINT uk_agent_trace_trace_id UNIQUE (trace_id),
    CONSTRAINT fk_agent_trace_conversation_id FOREIGN KEY (conversation_id) REFERENCES conversation (id),
    CONSTRAINT fk_agent_trace_message_id FOREIGN KEY (message_id) REFERENCES chat_message (id)
);

CREATE INDEX idx_agent_trace_conversation_created
    ON agent_trace (conversation_id, created_at DESC);

CREATE INDEX idx_agent_trace_status_created
    ON agent_trace (status, created_at DESC);
