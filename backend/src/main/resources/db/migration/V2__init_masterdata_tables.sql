CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    code VARCHAR(32) NOT NULL,
    name VARCHAR(64) NOT NULL,
    category VARCHAR(32),
    description TEXT,
    tags TEXT[],
    status VARCHAR(32) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_department_public_id UNIQUE (public_id),
    CONSTRAINT uk_department_code UNIQUE (code)
);

CREATE TABLE doctor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    department_id BIGINT NOT NULL,
    code VARCHAR(32),
    name VARCHAR(64) NOT NULL,
    title VARCHAR(64),
    specialty TEXT,
    intro TEXT,
    tags TEXT[],
    status VARCHAR(32) NOT NULL,
    consultation_fee NUMERIC(10, 2),
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_doctor_public_id UNIQUE (public_id),
    CONSTRAINT uk_doctor_code UNIQUE (code),
    CONSTRAINT fk_doctor_department_id FOREIGN KEY (department_id) REFERENCES department (id)
);

CREATE TABLE schedule_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    department_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    hospital_code VARCHAR(32),
    schedule_date DATE NOT NULL,
    period_code VARCHAR(32) NOT NULL,
    start_time TIME,
    end_time TIME,
    total_quota INTEGER NOT NULL,
    available_quota INTEGER NOT NULL,
    reserved_quota INTEGER NOT NULL DEFAULT 0,
    fee NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    source_type VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_schedule_slot_public_id UNIQUE (public_id),
    CONSTRAINT uk_slot_doctor_date_period UNIQUE (doctor_id, schedule_date, period_code),
    CONSTRAINT fk_schedule_slot_department_id FOREIGN KEY (department_id) REFERENCES department (id),
    CONSTRAINT fk_schedule_slot_doctor_id FOREIGN KEY (doctor_id) REFERENCES doctor (id),
    CONSTRAINT ck_schedule_slot_total_quota CHECK (total_quota >= 0),
    CONSTRAINT ck_schedule_slot_available_quota CHECK (available_quota >= 0),
    CONSTRAINT ck_schedule_slot_reserved_quota CHECK (reserved_quota >= 0),
    CONSTRAINT ck_schedule_slot_available_within_total CHECK (available_quota <= total_quota)
);

CREATE INDEX idx_department_status_sort ON department (status, sort_order, id);
CREATE INDEX idx_doctor_department_status ON doctor (department_id, status, id);
CREATE INDEX idx_schedule_slot_department_date_status ON schedule_slot (department_id, schedule_date, status);
CREATE INDEX idx_schedule_slot_doctor_date_status ON schedule_slot (doctor_id, schedule_date, status);
CREATE INDEX idx_schedule_slot_date_status ON schedule_slot (schedule_date, status);
