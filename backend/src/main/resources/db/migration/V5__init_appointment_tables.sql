CREATE TABLE appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    appointment_no VARCHAR(32) NOT NULL,
    user_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    schedule_date DATE NOT NULL,
    period_code VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    source_channel VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(64),
    booked_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    cancel_reason VARCHAR(255),
    cancel_source VARCHAR(32),
    remark VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_appointment_public_id UNIQUE (public_id),
    CONSTRAINT uk_appointment_no UNIQUE (appointment_no),
    CONSTRAINT fk_appointment_user_id FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_appointment_slot_id FOREIGN KEY (slot_id) REFERENCES schedule_slot (id),
    CONSTRAINT fk_appointment_department_id FOREIGN KEY (department_id) REFERENCES department (id),
    CONSTRAINT fk_appointment_doctor_id FOREIGN KEY (doctor_id) REFERENCES doctor (id)
);

CREATE UNIQUE INDEX uk_appointment_user_idempotency
    ON appointment (user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE INDEX idx_appointment_user_created ON appointment (user_id, created_at DESC);
CREATE INDEX idx_appointment_slot_status ON appointment (slot_id, status);
CREATE INDEX idx_appointment_status_date ON appointment (status, schedule_date);

CREATE TABLE appointment_operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    operation_type VARCHAR(32) NOT NULL,
    operator_type VARCHAR(32) NOT NULL,
    operator_id BIGINT,
    request_id VARCHAR(64),
    before_status VARCHAR(32),
    after_status VARCHAR(32),
    detail_json JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_appointment_operation_log_appointment_id FOREIGN KEY (appointment_id) REFERENCES appointment (id)
);

CREATE INDEX idx_appointment_op_appointment_created
    ON appointment_operation_log (appointment_id, created_at DESC);
