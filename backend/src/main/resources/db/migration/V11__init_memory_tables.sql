CREATE TABLE conversation_summary (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    conversation_id BIGINT NOT NULL,
    summary_text TEXT NOT NULL DEFAULT '',
    summary_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    business_state_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_message_count INTEGER NOT NULL DEFAULT 0,
    last_summarized_at TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_conversation_summary_public_id UNIQUE (public_id),
    CONSTRAINT uk_conversation_summary_conversation_id UNIQUE (conversation_id),
    CONSTRAINT fk_conversation_summary_conversation_id FOREIGN KEY (conversation_id) REFERENCES conversation (id)
);

CREATE INDEX idx_conversation_summary_updated_at
    ON conversation_summary (updated_at DESC);

CREATE TABLE user_memory_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL,
    memory_type VARCHAR(64) NOT NULL,
    memory_key VARCHAR(128) NOT NULL,
    summary VARCHAR(255) NOT NULL,
    value_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    confidence NUMERIC(5, 2) NOT NULL DEFAULT 0,
    source VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    last_confirmed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_accessed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_user_memory_profile_public_id UNIQUE (public_id),
    CONSTRAINT uk_user_memory_profile_user_type_key UNIQUE (user_id, memory_type, memory_key),
    CONSTRAINT fk_user_memory_profile_user_id FOREIGN KEY (user_id) REFERENCES user_account (id)
);

CREATE INDEX idx_user_memory_profile_user_status
    ON user_memory_profile (user_id, status, updated_at DESC);

CREATE INDEX idx_user_memory_profile_type_status
    ON user_memory_profile (memory_type, status, updated_at DESC);
