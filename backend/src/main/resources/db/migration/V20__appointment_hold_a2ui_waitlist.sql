ALTER TABLE schedule_slot
    ADD CONSTRAINT ck_schedule_slot_available_reserved_within_total
    CHECK (available_quota + reserved_quota <= total_quota);

ALTER TABLE appointment ADD COLUMN hold_id BIGINT;

CREATE TABLE appointment_hold (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    snapshot_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    confirmed_appointment_id BIGINT,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_appointment_hold_public_id UNIQUE (public_id),
    CONSTRAINT uk_appointment_hold_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT fk_appointment_hold_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_appointment_hold_slot FOREIGN KEY (slot_id) REFERENCES schedule_slot (id),
    CONSTRAINT fk_appointment_hold_confirmed FOREIGN KEY (confirmed_appointment_id) REFERENCES appointment (id),
    CONSTRAINT ck_appointment_hold_status CHECK (status IN ('PENDING_CONFIRMATION', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);

CREATE INDEX idx_appointment_hold_expiry ON appointment_hold (status, expires_at);

CREATE TABLE a2ui_action (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    hold_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    surface_id VARCHAR(96) NOT NULL,
    action_type VARCHAR(32) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_a2ui_action_public_id UNIQUE (public_id),
    CONSTRAINT uk_a2ui_action_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_a2ui_action_hold FOREIGN KEY (hold_id) REFERENCES appointment_hold (id),
    CONSTRAINT fk_a2ui_action_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT ck_a2ui_action_status CHECK (status IN ('PENDING', 'CONSUMED', 'CANCELLED', 'EXPIRED'))
);

CREATE TABLE waitlist_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    priority INTEGER NOT NULL DEFAULT 0,
    offered_hold_id BIGINT,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_waitlist_entry_public_id UNIQUE (public_id),
    CONSTRAINT fk_waitlist_entry_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_waitlist_entry_slot FOREIGN KEY (slot_id) REFERENCES schedule_slot (id),
    CONSTRAINT fk_waitlist_entry_hold FOREIGN KEY (offered_hold_id) REFERENCES appointment_hold (id),
    CONSTRAINT ck_waitlist_entry_status CHECK (status IN ('WAITING', 'OFFERED', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);

CREATE UNIQUE INDEX uk_waitlist_active_membership
    ON waitlist_entry (user_id, slot_id)
    WHERE status IN ('WAITING', 'OFFERED');
