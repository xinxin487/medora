CREATE TABLE conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL,
    title VARCHAR(128) NOT NULL,
    scene_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    last_message_at TIMESTAMPTZ,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_conversation_public_id UNIQUE (public_id),
    CONSTRAINT fk_conversation_user_id FOREIGN KEY (user_id) REFERENCES user_account (id)
);

CREATE INDEX idx_conversation_user_last_message
    ON conversation (user_id, last_message_at DESC NULLS LAST, created_at DESC);

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    conversation_id BIGINT NOT NULL,
    role VARCHAR(32) NOT NULL,
    message_type VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    client_message_id VARCHAR(128),
    tool_call_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    citation_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    token_usage_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_chat_message_public_id UNIQUE (public_id),
    CONSTRAINT fk_chat_message_conversation_id FOREIGN KEY (conversation_id) REFERENCES conversation (id)
);

CREATE UNIQUE INDEX uk_chat_message_conversation_client_message
    ON chat_message (conversation_id, client_message_id)
    WHERE client_message_id IS NOT NULL;

CREATE INDEX idx_chat_message_conversation_created
    ON chat_message (conversation_id, created_at ASC, id ASC);
