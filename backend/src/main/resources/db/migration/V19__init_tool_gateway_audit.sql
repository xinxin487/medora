CREATE TABLE tool_gateway_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id BIGINT,
    tool_name VARCHAR(128) NOT NULL,
    tool_version VARCHAR(32) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    risk_level VARCHAR(32) NOT NULL,
    agent_name VARCHAR(64),
    conversation_id VARCHAR(128),
    trace_id VARCHAR(128),
    request_id VARCHAR(128),
    status VARCHAR(32) NOT NULL,
    error_code VARCHAR(64),
    duration_ms BIGINT NOT NULL,
    arguments_hash VARCHAR(64) NOT NULL,
    arguments_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_tool_gateway_audit_public_id UNIQUE (public_id)
);

CREATE INDEX idx_tool_gateway_audit_created_at ON tool_gateway_audit (created_at DESC);
CREATE INDEX idx_tool_gateway_audit_tool_created ON tool_gateway_audit (tool_name, created_at DESC);
CREATE INDEX idx_tool_gateway_audit_trace_id ON tool_gateway_audit (trace_id);
