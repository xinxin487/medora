CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    username VARCHAR(64),
    mobile VARCHAR(20),
    email VARCHAR(128),
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    register_source VARCHAR(32) NOT NULL,
    last_login_at TIMESTAMPTZ,
    last_login_ip VARCHAR(64),
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_user_account_public_id UNIQUE (public_id),
    CONSTRAINT ck_user_account_identifier CHECK (mobile IS NOT NULL OR email IS NOT NULL)
);

CREATE UNIQUE INDEX uk_user_account_mobile
    ON user_account (mobile)
    WHERE mobile IS NOT NULL;

CREATE UNIQUE INDEX uk_user_account_email
    ON user_account (LOWER(email))
    WHERE email IS NOT NULL;

CREATE TABLE user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    gender VARCHAR(16),
    birth_date DATE,
    default_hospital_code VARCHAR(32),
    default_department_id BIGINT,
    preference_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_user_profile_user_id UNIQUE (user_id),
    CONSTRAINT fk_user_profile_user_id FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_user_profile_default_department_id FOREIGN KEY (default_department_id) REFERENCES department (id)
);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_user_id FOREIGN KEY (user_id) REFERENCES user_account (id)
);

CREATE INDEX idx_refresh_token_user_status ON refresh_token (user_id, status, expires_at);
