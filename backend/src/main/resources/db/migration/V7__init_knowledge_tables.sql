CREATE TABLE knowledge_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    title VARCHAR(255) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    source_uri VARCHAR(500),
    biz_scope VARCHAR(32) NOT NULL,
    department_tags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    doctor_tags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    version_no INTEGER NOT NULL DEFAULT 1,
    publish_status VARCHAR(32) NOT NULL,
    ingest_status VARCHAR(32) NOT NULL,
    content_hash VARCHAR(64),
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    uploaded_by BIGINT,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_knowledge_document_public_id UNIQUE (public_id),
    CONSTRAINT fk_knowledge_document_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES user_account (id)
);

CREATE INDEX idx_knowledge_document_status
    ON knowledge_document (publish_status, ingest_status, biz_scope);

CREATE TABLE knowledge_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    chunk_index INTEGER NOT NULL,
    section_path VARCHAR(255),
    content TEXT NOT NULL,
    content_tsv TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', content)) STORED,
    embedding_model VARCHAR(64),
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_knowledge_chunk_document_index UNIQUE (document_id, chunk_index),
    CONSTRAINT fk_knowledge_chunk_document_id FOREIGN KEY (document_id) REFERENCES knowledge_document (id)
);

CREATE INDEX idx_knowledge_chunk_document_status
    ON knowledge_chunk (document_id, status, chunk_index);

CREATE INDEX idx_knowledge_chunk_content_tsv
    ON knowledge_chunk USING GIN (content_tsv);

CREATE TABLE knowledge_ingest_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    task_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    error_message VARCHAR(500),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_knowledge_ingest_task_document_id FOREIGN KEY (document_id) REFERENCES knowledge_document (id)
);

CREATE INDEX idx_knowledge_ingest_task_document
    ON knowledge_ingest_task (document_id, created_at DESC);
